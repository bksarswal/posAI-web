import { execSync } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs';

const source = process.env.OPENAPI_SOURCE || '../posai-api/openapi.json';
const outputDir = path.resolve(process.cwd(), 'src/shared/types');
const outputFile = path.join(outputDir, 'api.d.ts');

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

console.log(`Generating API types from "${source}" into "${outputFile}"...`);

execSync(`npx openapi-typescript "${source}" -o "${outputFile}"`, {
  stdio: 'inherit',
});

const content = fs.readFileSync(outputFile, 'utf8');
const header = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not edit this file by hand. Run 'npm run api:types' to regenerate.
 */\n\n`;

if (!content.startsWith('/**\n * This file was auto-generated')) {
  fs.writeFileSync(outputFile, header + content, 'utf8');
}

console.log('✅ API types generated successfully.');
